"""
The engine-neutral contracts: what an adapter observes and measures, and what an executor may change.

An adapter uses the target's *observer* identity (read-only by role default
and by session setting) and its *measurement* identity (no ownership; writes
always rolled back). It sends no DDL. Changes go through an executor -- the
only holder of the operator identity -- and only as typed commands
(executor.CreateIndex / DropOwnIndex / AnalyzeTable). A SQL Server
implementation would provide these two protocols; nothing above this layer
knows which engine it is talking to.
"""
from __future__ import annotations

from typing import Any, Protocol

from ..model import ExplainResult, IndexState
from ..targets import TargetConfig


class DatabaseAdapter(Protocol):
    engine: str
    target: TargetConfig

    def bind_operation(self, operation_id: str | None) -> None: ...

    # --- observation (observer identity) ---------------------------------
    def identity(self) -> dict: ...
    def discover(self) -> dict: ...
    def table_facts(self, schema: str, table: str) -> dict: ...
    def column_statistics(self, schema: str, table: str, columns: list[str]) -> dict[str, dict]: ...
    def running_transactions(self) -> list[dict]: ...
    def index_state(self, schema: str, name: str) -> IndexState | None: ...
    def fieldhorizon_indexes(self) -> list[IndexState]: ...
    def invalid_indexes(self) -> list[dict]: ...
    def lease_state(self, scope: str) -> dict: ...
    def ledger_rows(self, *, unfinished_only: bool = False) -> list[dict]: ...
    def fieldhorizon_activity(self) -> list[dict]: ...
    def index_build_progress(self) -> list[dict]: ...
    def state_snapshot(self, schemas: tuple[str, ...] = ("bench",)) -> dict: ...
    def statement_statistics(self, limit: int = 25) -> dict: ...
    def maintenance_activity(self) -> list[dict]: ...

    # --- measurement (measure identity) ----------------------------------
    def explain(self, query: str, params: dict | None = None, *, write: bool = False) -> ExplainResult: ...
    def execute_timed(self, query: str, params: dict | None = None, *, write: bool = False) -> float: ...

    def close(self) -> None: ...


class Executor(Protocol):
    target: TargetConfig
    lease: Any

    def acquire(self) -> Any: ...
    def heartbeat(self) -> None: ...
    def release(self) -> None: ...
    def close(self) -> None: ...
    def authorize(self, *, eligibility: dict | None = None) -> Any: ...
    def verify_authorization(self, auth: Any, operation: str, *, compensation: bool = False) -> None: ...
    def ledger_row(self, operation_id: str, change_id: str) -> dict | None: ...
    def create_index(self, auth: Any, cmd: Any) -> IndexState: ...
    def drop_own_index(self, auth: Any, cmd: Any, *, compensation: bool = True) -> dict: ...
    def mark_retained(self, auth: Any, change_id: str) -> None: ...
    def analyze_table(self, auth: Any, cmd: Any) -> None: ...
    def vacuum_table(self, auth: Any, cmd: Any) -> None: ...
